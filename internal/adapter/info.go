package adapter

import (
	"path/filepath"
	"strings"
)

// Info is the listing metadata for one session, extracted in a single parse.
type Info struct {
	SessionID string
	Project   string
	Title     string
	FirstTs   int64
	LastTs    int64 // from record timestamps; callers usually prefer file mtime
	MsgCount  int
	Mode      string
}

// ReadInfo parses a session file once and returns its listing metadata. The
// session_meta refresh only calls this for new/changed files, so the full-parse
// cost is paid only when a file actually changes.
func ReadInfo(sf SessionFile) (Info, error) {
	recs, err := Parse(sf)
	if err != nil {
		return Info{}, err
	}
	info := Info{Mode: Mode(sf.Path, sf.Source), MsgCount: len(recs)}
	if len(recs) > 0 {
		info.SessionID = recs[0].SessionID
		info.Project = recs[0].Project
		info.Title = recs[0].Title
		var first, last int64
		for _, r := range recs {
			if r.Timestamp <= 0 {
				continue
			}
			if first == 0 || r.Timestamp < first {
				first = r.Timestamp
			}
			if r.Timestamp > last {
				last = r.Timestamp
			}
		}
		info.FirstTs, info.LastTs = first, last
	}
	if info.SessionID == "" {
		info.SessionID = sessionIDFromPath(sf)
	}
	if strings.TrimSpace(info.Title) == "" {
		info.Title = firstUserTitle(recs)
	}
	return info, nil
}

// sessionIDFromPath recovers a session id from the filename when a transcript
// has no parseable message records yet (brand-new session).
func sessionIDFromPath(sf SessionFile) string {
	base := strings.TrimSuffix(filepath.Base(sf.Path), ".jsonl")
	if sf.Source == "codex" {
		// rollout-<timestamp>-<uuid>: the uuid is the trailing 5 hyphen groups.
		if parts := strings.Split(base, "-"); len(parts) >= 5 {
			return strings.Join(parts[len(parts)-5:], "-")
		}
	}
	return base
}

// firstUserTitle derives a title from the first real user message, skipping
// harness-injected blocks (used when the tool recorded no title).
func firstUserTitle(recs []Record) string {
	for _, r := range recs {
		if r.Role != "user" {
			continue
		}
		t := strings.TrimSpace(r.Text)
		if t == "" || isInjectedText(t) {
			continue
		}
		return firstLine(t, 80)
	}
	return ""
}

func isInjectedText(t string) bool {
	for _, m := range []string{
		"# AGENTS.md", "<INSTRUCTIONS>", "<environment_context>", "<permissions",
		"<user_instructions>", "<system-reminder>", "<command-name>", "<command-message>",
		"<local-command-stdout>", "Caveat: The messages below were generated by the user",
	} {
		if strings.HasPrefix(t, m) {
			return true
		}
	}
	return false
}
